export const getMockTestResult = (answers: TTestAnswers): TTestResult => {
  const totalScore = Object.values(answers).reduce(
    (sum, optionId) => sum + (optionScores[optionId] ?? 0),
    0,
  );

  const range = mockTestResultRanges.find(
    ({ minScore, maxScore }) => totalScore >= minScore && totalScore <= maxScore,
  );

  return (range ?? mockTestResultRanges[mockTestResultRanges.length - 1]).result;
};
